"""Run the frozen A/B/C model-bottleneck diagnostic over pinned SWE-Gym development tasks.

The diagnostic asks one question per condition, holding model, prompt, tools, decoding, step
budget and seed fixed:

* ``A`` autonomous - the stock prompt and tools, with the real baseline failure text.
* ``B`` oracle-file - A plus one extra user message naming the implementation files the reviewed
  repair touches. Paths only: no diff, no target code, no explanation.
* ``C`` oracle-context - B plus a real numbered source window of those files at the task's base
  commit, generated by ``scripts/build_diagnostic_oracle.py`` under a fixed window rule.

What the three conditions can and cannot show is fixed in advance:

* B and C are *assisted* diagnostics. A pass under B or C is not autonomous capability, and the
  report must say so wherever it is quoted.
* C estimates what this assist buys, not the model's ceiling: the window is chosen from the
  repair's position and can still miss a dependency the fix needs.
* The auxiliary text is a separate message with its own sha256, never a fabricated tool result.
  No ``read_file`` or ``search_text`` step is invented, and the environment's real read-before-edit
  and verifier-owned-test boundaries are unchanged.

Trials are interleaved on a pre-fixed order (repetition, then task, then condition) so that time
drift is spread across conditions instead of accumulating inside one of them, and every trial gets
a fresh isolated container. Each trial has a hard wall-clock timeout; a timeout is recorded as an
infrastructure failure and is never silently retried or replaced.
"""

